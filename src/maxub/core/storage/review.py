"""Переходы очереди по решению человека.

Отделено от [delivery][maxub.core.storage.delivery] по тому, кто распоряжается
записью. Там переходы совершает воркер, и они обратимы: захватил, не смог,
вернул. Здесь — окончательные решения человека, разбирающего то, что платформа
не решилась сделать сама, и каждый из них закрывает запись навсегда.

Все переходы разрешены только из ``failed``. Это не перестраховка: запись в
живом состоянии принадлежит воркеру, и забрать её у него означало бы отправить
сообщение дважды либо потерять его.
"""

from __future__ import annotations

from maxub.core.models import Event, OutboxState, utcnow
from maxub.core.storage.delivery import DeliveryMixin


class ReviewMixin(DeliveryMixin):
    """Решения человека поверх обычного жизненного цикла доставки."""

    async def mark_sent_after_review(
        self, item_id: int, remote_message_id: str, event: Event
    ) -> bool:
        """Закрывает отказавшую запись, когда сверка нашла сообщение на сервере.

        Отдельный метод, а не параметр соседнего: исходное состояние здесь
        другое — запись уже отдана человеку, и «в полёте» её больше нет.
        Условие по состоянию остаётся обязательным: между чтением записи и этим
        вызовом стоит сетевая сверка, за время которой запись мог разобрать
        второй оператор.
        """
        return await self._close_as_sent(item_id, remote_message_id, event, OutboxState.FAILED)

    async def requeue(self, item_id: int) -> bool:
        """Возвращает отказавшую запись в очередь по решению человека.

        Разрешено только из ``failed``: остальные состояния принадлежат воркеру,
        и отобрать у него запись посреди отправки — прямой путь к дублю у
        получателя. Состояние проверяет сама СУБД: между чтением записи и этим
        вызовом успевает пройти сетевая сверка, поэтому ``False`` означает
        «состояние уже не то», и повторять после него вслепую нельзя.

        Счётчик попыток обнуляется. Отказавшая запись обычно упёрлась в лимит, а
        [claim_queued][maxub.core.storage.delivery.DeliveryMixin.claim_queued]
        засчитывает попытку ещё до отправки — без сброса воркер закрыл бы запись
        отказом, не дойдя до транспорта, и ручной повтор оказался бы фикцией.
        Бесконечным цикл не станет: каждый повтор требует отдельного решения
        человека. Следы прошлой попытки стираются вместе со счётчиком — они
        описывают разбор, который уже закончился.
        """
        async with self.write() as db:
            cursor = await db.execute(
                "UPDATE outbox SET state = ?, attempts = 0, error = NULL,"
                " next_attempt_at = NULL, claimed_at = NULL"
                " WHERE id = ? AND state = ?",
                (OutboxState.QUEUED.value, item_id, OutboxState.FAILED.value),
            )
        return cursor.rowcount == 1

    async def discard(self, item_id: int, reason: str, event: Event) -> bool:
        """Закрывает отказавшую запись без отправки и пишет событие об этом.

        Условие по состоянию то же, что у
        [requeue][maxub.core.storage.delivery.DeliveryMixin.requeue], и по той же
        причине: пока записью распоряжается воркер, отобрать её нельзя — здесь
        отказ обошёлся бы не дублем, а молча отменённой отправкой, о которой
        отправителю уже ответили «принято».

        ``error`` остаётся нетронутым: причина отказа отправки и причина решения
        человека отвечают на разные вопросы, и второе не должно стирать первое —
        именно за этим к записи и возвращаются через месяцы.

        Событие пишется той же транзакцией, что и смена состояния, — как у
        отправки: иначе падение между ними навсегда оставило бы решение человека
        без следа в журнале, откуда его уже не восстановить.

        Возвращает, как и закрытие отправки, признак «есть что публиковать»:
        отказ, который журнал уже знает, второй раз подписчику не показывают.
        Состоялся ли сам переход, вызывающий узнаёт из состояния записи — там
        видно и то, чем закончился параллельный разбор.
        """
        async with self.write() as db:
            cursor = await db.execute(
                "UPDATE outbox SET state = ?, discard_reason = ?, discarded_at = ?"
                " WHERE id = ? AND state = ?",
                (
                    OutboxState.DISCARDED.value,
                    reason,
                    utcnow().isoformat(),
                    item_id,
                    OutboxState.FAILED.value,
                ),
            )
            if cursor.rowcount != 1:
                return False
            return await self.insert_event(event)
