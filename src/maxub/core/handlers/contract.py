"""Контракт точки расширения: входящее событие → обработчик → действие.

Плагины как отдельная поставка (загрузка через `entry_points`, каталог, версии)
отложены за пределы v1. Сам контракт — нет: у Ultroid и PagerMaid плагины и
мультиаккаунт дописывались поверх готовой платформы и остались полусломанными
именно потому, что договориться о границе было уже поздно. Здесь граница
фиксируется до того, как появится первый обработчик.

Из чего состоит договор:

* обработчик получает **уже записанное** событие из журнала вместе с его
  номером — не подписку в памяти. Значит, перезапуск демона не теряет работу, а
  событие приходит хотя бы один раз;
* действовать обработчик может только через `HandlerContext`. Прямого доступа
  к транспорту у него нет: любая отправка идёт общей очередью, а значит через
  те же лимиты, ту же идемпотентность и тот же ручной разбор, что и всё
  остальное. Обработчик, обходящий лимиты, — это забаненный аккаунт;
* обработчик объявляет, какие события ему нужны (`kinds`) и какие возможности
  транспорта требуются (`requires`). Первое избавляет от разбора чужих событий,
  второе не даёт молча ничего не делать там, где транспорт не умеет нужного.

Чего в контракте нет намеренно: доступа к базе, к настройкам демона и к другим
аккаунтам помимо того, который указан в событии, — отправка привязана к аккаунту
события, и выбрать другой обработчик не может. Служебные события самого
диспетчера (`handler.*`) обработчикам тоже не раздаются: обработчик, падающий на
собственном отказе, порождал бы отказы бесконечно. Всё это появится, когда
появится обработчик, которому оно действительно нужно, — а не «на всякий
случай».
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from maxub.core.models import Event
from maxub.transport.base import Capabilities


class HandlerError(Exception):
    """Обработчик не смог выполнить действие."""


class HandlerContext(Protocol):
    """Всё, что обработчику разрешено сделать с внешним миром."""

    #: Номер события в журнале. Он же — основа ключа идемпотентности действия.
    event_id: int

    @property
    def account_id(self) -> int | None:
        """Аккаунт события — единственный, от чьего имени можно действовать.

        Только на чтение: изменяемое поле обработчик мог бы переписать перед
        отправкой и написать от чужого имени, а весь смысл привязки в том, что
        выбора у него нет.
        """
        ...

    async def send_text(self, chat_id: str, text: str) -> int:
        """Ставит сообщение в общую очередь отправки и отдаёт номер записи.

        Отправка идёт от аккаунта, которому принадлежит событие: выбирать
        аккаунт обработчик не может. Событие без аккаунта отправлять не от кого,
        и такой вызов — `HandlerError`.

        Ключ идемпотентности выводится из имени обработчика, номера события и
        порядкового номера вызова внутри обработки. Поэтому повтор события
        после перезапуска не создаёт второго сообщения, а обработчик, которому
        нужно отправить два разных сообщения на одно событие, получает две
        записи, а не одну.
        """
        ...

    def capabilities(self) -> Capabilities | None:
        """Что умеет транспорт аккаунта; ``None`` — соединения сейчас нет."""
        ...


@runtime_checkable
class EventHandler(Protocol):
    """Обработчик события.

    Имя обязано быть постоянным: по нему хранится позиция в журнале. Смена
    имени равносильна появлению нового обработчика, который начнёт с текущего
    момента.
    """

    #: Уникальное имя. Оно же — ключ курсора и часть ключа идемпотентности.
    name: str

    #: Виды событий, которые обработчику интересны. Пустое множество означает
    #: «все» — так обработчику-наблюдателю не приходится перечислять весь
    #: список видов, чтобы ничего не пропустить.
    kinds: frozenset[str]

    #: Возможности транспорта, без которых обработчик бесполезен. Проверяются по
    #: аккаунту события: разные аккаунты могут работать разными адаптерами.
    requires: frozenset[str]

    async def handle(self, event: Event, context: HandlerContext) -> None:
        """Обрабатывает событие.

        Исключение отсюда — это «не получилось, попробуйте ещё раз»: диспетчер
        повторит событие несколько раз и только потом отложит его, записав отказ
        в журнал. Возврат без исключения означает «сделано», и курсор двигается
        вперёд.
        """
        ...
