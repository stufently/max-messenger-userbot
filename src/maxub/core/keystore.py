"""Ключ шифрования сессий в хранилище операционной системы.

Файл `secret.key` рядом с базой закрывает утечку копии тома: украли базу без
ключа — она бесполезна. Но от того, кто добрался до самого каталога, он не
защищает никак, ключ там лежит открытым текстом. Хранилища ОС закрывают именно
этот зазор: ключ становится доступен только тому же пользователю на той же
машине.

Здесь — политика: какой источник ключа главнее, что делать при отказе хранилища
и как согласовать хранилище с уже лежащим рядом файлом. Сами хранилища (Windows
DPAPI, Linux Secret Service) живут в
[keystore_backends][maxub.core.keystore_backends] за протоколом
[KeyStore][maxub.core.keystore.KeyStore].

Граница проведена так не ради размера файла: платформенные вызовы невозможно
выполнить в Linux-контейнере, где идут проверки, а политику — где и решаются
вопросы вроде «не завести ли новый ключ поверх живой базы» — проверять
обязательно. Над протоколом она тестируется на подменённом хранилище целиком.

Отсутствие хранилища — штатный случай, а не ошибка. Демон в Docker никакого
Secret Service не увидит и обязан работать ровно как раньше, файлом.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Protocol

from maxub.core.crypto import generate_key

log = logging.getLogger(__name__)

#: Текст следа, который остаётся вместо удалённого `secret.key`. Ключа в нём
#: нет — только сведения о том, куда он уехал и как вернуться.
MOVED_NOTE = (
    "Ключ шифрования сессий перенесён в хранилище ОС ({store}),"
    " файл secret.key удалён по MAXUB_SECRET_KEY_DROP_FILE.\n"
    "Чтобы вернуться к файлу: выньте ключ из хранилища, положите его в"
    " secret.key и удалите этот файл.\n"
)


class KeyStoreError(Exception):
    """Хранилище есть, но ответило отказом.

    Отличается от «хранилища нет»: первое — повод отступить к файлу с записью в
    журнал, второе — обычный путь, о котором нечего сообщать.
    """


class SecretKeyConflict(Exception):
    """В хранилище и в файле лежат разные ключи.

    Молча выбрать любой из них — значит с высокой вероятностью сделать сессии
    в базе нечитаемыми, поэтому демон отказывается стартовать и просит человека
    решить, какой ключ настоящий.
    """


class KeyStore(Protocol):
    """Минимум, который нужен от хранилища: прочитать и записать ключ."""

    name: str

    def load(self) -> str | None: ...

    def save(self, key: str) -> None: ...


def write_blob(path: Path, data: bytes) -> None:
    """Пишет двоичный секрет с правами 0600 и без промежуточного состояния.

    Сначала временный файл рядом, потом `os.replace`: оборванная запись прямо в
    целевой файл оставила бы половину конверта, а половина конверта — это
    потерянный ключ и нечитаемые сессии.
    """
    tmp = path.with_name(path.name + ".tmp")
    nofollow = getattr(os, "O_NOFOLLOW", 0)
    fd = os.open(tmp, os.O_CREAT | os.O_TRUNC | os.O_WRONLY | nofollow, 0o600)
    try:
        written = 0
        # `os.write` вправе записать не всё за раз; для ключа «не всё» означает
        # мусор вместо конверта, поэтому дописываем в цикле.
        while written < len(data):
            written += os.write(fd, data[written:])
    finally:
        os.close(fd)
    os.replace(tmp, path)


def moved_marker(key_path: Path) -> Path:
    """След переноса ключа в хранилище ОС.

    Пустой каталог и каталог, из которого ключ уехал в хранилище, снаружи
    выглядят одинаково. Без этой пометки демон, потерявший доступ к хранилищу,
    решил бы, что это первый запуск, и завёл бы новый ключ поверх живой базы.
    """
    return key_path.with_name(key_path.name + ".moved")


class SecretKeyMissing(Exception):
    """Ключа нет нигде, а сессии в базе есть.

    Завести новый ключ в такой ситуации — значит объявить все сохранённые
    сессии нечитаемыми и не сказать об этом ни слова. Демон отказывается
    стартовать и оставляет решение человеку: у него ключ может быть в резервной
    копии, в другом профиле или в `MAXUB_SECRET_KEY`.
    """


def resolve_key(
    store: KeyStore, key_path: Path, *, drop_file: bool = False, may_create: bool = True
) -> str | None:
    """Согласует ключ в хранилище ОС с файлом рядом с базой.

    `None` значит «хранилище отказало» — вызывающий продолжает работать файлом.

    `may_create` запрещает заводить новый ключ. Пустое хранилище само по себе не
    означает первый запуск: ключ мог потеряться вместе с профилем или связкой, а
    база с сессиями при этом никуда не делась. Отличить одно от другого отсюда
    нельзя — знает вызывающий, он и решает.

    Миграция существующей установки сделана копированием, а не переносом: ключ
    из `secret.key` кладётся в хранилище, а файл остаётся на месте. Молча
    удалить его нельзя — пользователь потеряет и откат на прежнюю версию, и
    доступ к сессиям, если хранилище пропадёт (переустановка системы, сброс
    связки ключей, смена пароля учётной записи Windows). Плата за это честная:
    пока файл лежит рядом, выигрыша в защите нет. Убрать его — отдельное явное
    решение (`drop_file`), и только после того, как ключ прочитан из хранилища
    обратно. Обратимость сохраняется: ключ жив в хранилище, а `MAXUB_SECRET_KEY`
    старше любого хранилища, поэтому вернуться к файлу можно всегда.
    """
    file_key = key_path.read_text(encoding="utf-8").strip() if key_path.exists() else ""
    try:
        stored = store.load()
        if stored is None:
            if not file_key and not may_create:
                raise SecretKeyMissing(
                    f"в хранилище {store.name} ключа нет, файла тоже, а база с сессиями"
                    " уже есть: новый ключ сделал бы их нечитаемыми."
                    " Восстановите ключ или задайте MAXUB_SECRET_KEY"
                )
            store.save(file_key or generate_key())
            # Перечитываем вместо того, чтобы поверить записи: убеждаемся, что
            # ключ действительно достаётся обратно, — только после этого его
            # можно считать пригодным, а файл рядом удалять. Заодно снимается
            # часть гонки: чужую запись мы увидим вместо своей. Полностью гонку
            # это не решает — «создать, если нет» ни DPAPI, ни Secret Service не
            # умеют, — но два демона на одном каталоге данных и без того
            # несовместимы: их разводит одиночный запуск, а не этот код.
            stored = store.load()
    except KeyStoreError as exc:
        log.warning("хранилище ключей %s недоступно (%s), работаем файлом", store.name, exc)
        return None
    if not stored:
        log.warning("хранилище ключей %s не вернуло записанный ключ", store.name)
        return None
    if file_key and file_key != stored:
        raise SecretKeyConflict(
            f"ключ в хранилище ОС и в файле {key_path} разные;"
            " укажите нужный в MAXUB_SECRET_KEY или оставьте только один источник"
        )
    if file_key and drop_file:
        key_path.unlink()
        moved_marker(key_path).write_text(MOVED_NOTE.format(store=store.name), encoding="utf-8")
        log.info("ключ шифрования перенесён в хранилище %s, файл удалён", store.name)
    return stored
