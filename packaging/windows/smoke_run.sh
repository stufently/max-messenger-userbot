#!/usr/bin/env bash
# Запуск собранного exe: проверяет, что он вообще стартует и говорит по-русски.
#
# Зачем отдельно от check_bundle.py. Тот разбирает архив внутри exe и отвечает
# на вопрос «всё ли положено внутрь». Запуск отвечает на другой: onefile
# разворачивает себя во временный каталог, поднимает интерпретатор и только
# потом доходит до импортов — сломанный загрузчик, недостающая системная
# библиотека или испорченная кодировка вывода выглядят как успешная сборка
# вплоть до первого запуска у пользователя.
#
# Один файл на два пути (CI на раннере и локальная сборка под Wine) по той же
# причине, по которой так сделан check_bundle.py: проверка, живущая только в
# workflow, локальной сборкой не выполняется и расходится с ней молча.
#
# Команда передаётся аргументами, а не собирается здесь: на раннере exe
# запускается напрямую, под Wine — через `xvfb-run wine`. `--help` дописывает
# скрипт, потому что проверяется именно справка: любой другой команде клиента
# нужен живой демон, а демон здесь не при чём.
set -euo pipefail

if [ "$#" -eq 0 ]; then
    echo "smoke_run.sh: нужна команда запуска exe" >&2
    exit 2
fi

LIMIT_SECONDS="${MAXUB_SMOKE_TIMEOUT:-120}"

# Вывод забирается через подстановку, то есть через конвейер, а не в файл: у
# Wine перенаправление stdout Windows-Python в обычный файл ломает инициализацию
# потоков («Invalid handle»), и проверка падала бы не на том, что проверяет.
#
# `timeout` есть не везде: в Git Bash на раннере GitHub coreutils урезан. Там
# ограничение по времени даёт сам GitHub через `timeout-minutes` у шага, а здесь
# запуск идёт как есть — лучше без ограничения, чем с отказом «команда не
# найдена» на ровном месте.
status=0
if command -v timeout >/dev/null 2>&1; then
    output="$(timeout "$LIMIT_SECONDS" "$@" --help 2>&1)" || status=$?
else
    output="$("$@" --help 2>&1)" || status=$?
fi

printf '%s\n' "$output"

if [ "$status" -ne 0 ]; then
    if [ "$status" -eq 124 ]; then
        echo "smoke_run.sh: exe не ответил за ${LIMIT_SECONDS} с" >&2
    else
        echo "smoke_run.sh: exe завершился с кодом $status" >&2
    fi
    exit 1
fi

if [ -z "$output" ]; then
    echo "smoke_run.sh: exe ничего не напечатал" >&2
    exit 1
fi

# Проверка байтами, а не словами. Искать конкретную строку справки значило бы
# привязать сборку к формулировке, которая меняется при первой правке текста;
# проверяется же не текст, а то, что кириллица дошла до вывода целой. 0xD0/0xD1 —
# ведущие байты кириллицы в UTF-8, 0xEF 0xBF 0xBD — символ замены, который
# появляется, когда вывод переводят в кодировку, где кириллицы нет (на этом
# сборка уже падала). `LC_ALL=C` — чтобы grep сравнивал байты, а не символы: в
# Git Bash локаль может быть какой угодно.
# Символ замены проверяется первым: он и есть точный признак «кодировку не
# осилили», а «кириллицы нет вовсе» — следствие, и сообщать о следствии, когда
# видна причина, значит уводить от неё.
if printf '%s' "$output" | LC_ALL=C grep -q -e $'\xef\xbf\xbd'; then
    echo "smoke_run.sh: в справке символ замены — вывод испорчен кодировкой" >&2
    exit 1
fi

if ! printf '%s' "$output" | LC_ALL=C grep -q -e $'\xd0' -e $'\xd1'; then
    echo "smoke_run.sh: в справке нет кириллицы — вывод потерял кодировку" >&2
    exit 1
fi

echo "smoke_run.sh: exe запускается, справка на месте"
